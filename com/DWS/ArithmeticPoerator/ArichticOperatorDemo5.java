package com.DWS.ArithmeticPoerator;

public class ArichticOperatorDemo5 {
    public static void main(String[] args) {
        //++和--
        int a=10;
        a++;
        System.out.println(a);//11
        ++a;
        System.out.println(a);//12
        a--;
        System.out.println(a);//11
        --a;
        System.out.println(a);//10

    }
}
